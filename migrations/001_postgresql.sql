-- Version 1: new private schema only. Fails if the schema already exists.
CREATE SCHEMA "gphem";
SET LOCAL search_path = "gphem", pg_catalog;
CREATE TABLE admins (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT COLLATE "C" NOT NULL UNIQUE, password_hash TEXT COLLATE "C" NOT NULL);
CREATE TABLE web_sessions (
 token_hash TEXT COLLATE "C" PRIMARY KEY, data TEXT COLLATE "C" NOT NULL, expires DOUBLE PRECISION NOT NULL);
CREATE TABLE rate_limits (
 key TEXT COLLATE "C" PRIMARY KEY, count BIGINT NOT NULL, resets DOUBLE PRECISION NOT NULL);
CREATE TABLE rooms (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, building TEXT COLLATE "C" NOT NULL, number TEXT COLLATE "C" NOT NULL,
 layout TEXT COLLATE "C" NOT NULL, version BIGINT NOT NULL DEFAULT 1, UNIQUE(building,number));
CREATE TABLE exams (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT COLLATE "C" NOT NULL, starts_at TEXT COLLATE "C" NOT NULL, timezone TEXT COLLATE "C" NOT NULL,
 show_names BIGINT NOT NULL DEFAULT 0, rules TEXT COLLATE "C" NOT NULL DEFAULT '[]', seed BIGINT NOT NULL DEFAULT 42,
 version BIGINT NOT NULL DEFAULT 1, draft_id BIGINT, approved_id BIGINT, published_id BIGINT,
 publication TEXT COLLATE "C" NOT NULL DEFAULT 'off' CHECK(publication IN ('off','manual','scheduled')),
 publish_at TEXT COLLATE "C", mode TEXT COLLATE "C" NOT NULL DEFAULT 'seating', shift TEXT COLLATE "C" NOT NULL DEFAULT '',
 gtu_date TEXT COLLATE "C" NOT NULL DEFAULT '', gtu_config TEXT COLLATE "C" NOT NULL DEFAULT '{}',
 gtu_disabled TEXT COLLATE "C" NOT NULL DEFAULT '[]', source TEXT COLLATE "C" NOT NULL DEFAULT 'spreadsheet',
 historical BIGINT NOT NULL DEFAULT 0, auto_publish BIGINT NOT NULL DEFAULT 0);
CREATE UNIQUE INDEX unique_gtu_session ON exams(gtu_date,shift) WHERE mode='gtu';
CREATE TABLE exam_rooms (
 exam_id BIGINT NOT NULL REFERENCES exams(id), room_id BIGINT NOT NULL REFERENCES rooms(id),
 PRIMARY KEY(exam_id,room_id));
CREATE TABLE students (
 exam_id BIGINT NOT NULL REFERENCES exams(id), sid TEXT COLLATE "C" NOT NULL, name TEXT COLLATE "C" NOT NULL,
 branch TEXT COLLATE "C" NOT NULL, batch TEXT COLLATE "C" NOT NULL, year TEXT COLLATE "C" NOT NULL,
 PRIMARY KEY(exam_id,sid));
CREATE TABLE imports (
 id TEXT COLLATE "C" PRIMARY KEY, exam_id BIGINT NOT NULL REFERENCES exams(id), admin_id BIGINT NOT NULL REFERENCES admins(id),
 version BIGINT NOT NULL, records TEXT COLLATE "C" NOT NULL, errors TEXT COLLATE "C" NOT NULL, created DOUBLE PRECISION NOT NULL);
CREATE TABLE revisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, exam_id BIGINT NOT NULL REFERENCES exams(id), input_version BIGINT NOT NULL,
 config TEXT COLLATE "C" NOT NULL, preview TEXT COLLATE "C" NOT NULL, metadata TEXT COLLATE "C" NOT NULL, exam_info TEXT COLLATE "C" NOT NULL, approved BIGINT NOT NULL DEFAULT 0,
 created TEXT COLLATE "C" NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), release_at TEXT COLLATE "C");
CREATE TABLE assignments (
 revision_id BIGINT NOT NULL REFERENCES revisions(id), sid TEXT COLLATE "C" NOT NULL, seat_id TEXT COLLATE "C" NOT NULL, payload TEXT COLLATE "C" NOT NULL,
 PRIMARY KEY(revision_id,sid), UNIQUE(revision_id,seat_id));
CREATE TABLE presets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT COLLATE "C" NOT NULL UNIQUE, rules TEXT COLLATE "C" NOT NULL);
CREATE TABLE audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, admin_id BIGINT REFERENCES admins(id), action TEXT COLLATE "C" NOT NULL,
 detail TEXT COLLATE "C" NOT NULL, created TEXT COLLATE "C" NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));
CREATE TABLE generation_errors (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, exam_id BIGINT NOT NULL REFERENCES exams(id), message TEXT COLLATE "C" NOT NULL,
 created TEXT COLLATE "C" NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));
CREATE TABLE gtu_settings (
 id BIGINT PRIMARY KEY CHECK(id=1), config TEXT COLLATE "C" NOT NULL, version BIGINT NOT NULL DEFAULT 1);
CREATE TABLE gtu_students (
 exam_id BIGINT NOT NULL, enrollment_no TEXT COLLATE "C" NOT NULL, exam_date TEXT COLLATE "C" NOT NULL,
 session TEXT COLLATE "C" NOT NULL, block_no TEXT COLLATE "C" NOT NULL, subject_code TEXT COLLATE "C" NOT NULL,
 subject_name TEXT COLLATE "C" NOT NULL, uploaded_at DOUBLE PRECISION NOT NULL, pdf_bench BIGINT, pdf_page BIGINT,
 PRIMARY KEY(exam_id,enrollment_no),
 FOREIGN KEY(exam_id,enrollment_no) REFERENCES students(exam_id,sid));
CREATE TABLE pdf_imports (
 id TEXT COLLATE "C" PRIMARY KEY, admin_id BIGINT NOT NULL REFERENCES admins(id), created DOUBLE PRECISION NOT NULL, payload TEXT COLLATE "C" NOT NULL);
CREATE TABLE emergency_admissions (
 exam_id BIGINT NOT NULL, sid TEXT COLLATE "C" NOT NULL, reason TEXT COLLATE "C" NOT NULL, admin_id BIGINT NOT NULL REFERENCES admins(id),
 created DOUBLE PRECISION NOT NULL, PRIMARY KEY(exam_id,sid),
 FOREIGN KEY(exam_id,sid) REFERENCES students(exam_id,sid));
CREATE TABLE pdf_sources (
 id TEXT COLLATE "C" PRIMARY KEY, content BYTEA NOT NULL, created DOUBLE PRECISION NOT NULL);
CREATE TABLE exam_pdf_sources (
 exam_id BIGINT PRIMARY KEY REFERENCES exams(id), source_id TEXT COLLATE "C" NOT NULL REFERENCES pdf_sources(id));
CREATE TABLE publication_overrides (
 exam_id BIGINT PRIMARY KEY REFERENCES exams(id), release_at TEXT COLLATE "C" NOT NULL);
CREATE TABLE emergency_seats (
 exam_id BIGINT NOT NULL, sid TEXT COLLATE "C" NOT NULL, seat_id TEXT COLLATE "C" NOT NULL,
 PRIMARY KEY(exam_id,sid), UNIQUE(exam_id,seat_id),
 FOREIGN KEY(exam_id,sid) REFERENCES students(exam_id,sid));
CREATE TABLE schema_migrations (version INTEGER PRIMARY KEY, checksum TEXT NOT NULL, applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
